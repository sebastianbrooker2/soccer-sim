"""Write eval/sensing/yoloErrorModel.m from calib tables and calib/k.json (inflation)."""
import pandas as pd, numpy as np, json, os
tb=pd.read_csv('calib/tab_ball.csv'); tr=pd.read_csv('calib/tab_robot.csv')
k=json.load(open("calib/k.json")) if os.path.exists("calib/k.json") else None
def v(a): return '['+' '.join('%.4g'%x for x in a)+']'
def blk(name,t,extra):
    s=f"m.{name}.s     = {v(t.s)};   % measured box size (ball: width, robot: height) [px], knots\n"
    s+=f"m.{name}.sTrue = {v(t.tm)};   % median true size at that measured size [px]\n"
    s+=f"m.{name}.sSd   = {v(t.tsd)};   % robust std of true size [px]\n"
    s+=f"m.{name}.vBias = {v(t.vb)};   % robust bias of the range row (ball centre / robot foot) [px]\n"
    s+=f"m.{name}.vSd   = {v(t.vsd)};   % robust std of that row [px]\n"
    s+=f"m.{name}.uSd   = {v(t.usd)};   % robust std of the box centre column [px]\n"
    return s
out="""function m = yoloErrorModel()
%YOLOERRORMODEL Calibrated YOLO box-error model (generated by tools/yolo/gen_model.py).
%   Fitted on recordings/real01 (dets_all.csv vs projected GT, tools/yolo/fit_tables.py,
%   fit_k.py).  Tables are indexed by the MEASURED box size and interpolated
%   (clamped at the ends).  The ball box is biased ~+1.7 px (true width = 0.8..0.9*w);
%   at long range (w<8 px) the detector box saturates, so the size cue is weak.
%   m.kR / m.kRes: heavy-tail inflation of the first-order range std so that
%   ~99%% of errors lie inside 3 sigma, indexed by the estimated range.
"""
out+=blk('ball',tb,'')+blk('robot',tr,'')
if k is None: k={'ball':{'r':[0,100],'k':[1,1],'conf':[[0,1.01]],'cf':[1]},'robot':{'r':[0,100],'k':[1,1],'conf':[[0,1.01]],'cf':[1]}}
for c in ['ball','robot']:
    out+=f"m.{c}.kR    = {v(k[c]['r'])};   % estimated range knots [m]\n"
    out+=f"m.{c}.kVal  = {v(k[c]['k'])};   % range-std inflation at those ranges\n"
    out+=f"m.{c}.cEdge = {v(k[c]['cedge'] if 'cedge' in k[c] else [0,1.01])};   % conf group edges\n"
    out+=f"m.{c}.cFac  = {v(k[c]['cf'])};   % extra std factor per conf group\n"
lq=k.get('lqFac',1.0); kb=k.get('kB',{'ball':1.0,'robot':1.0})
out+=f"""% validity rule (ball): low quality if the box is too small / not round / low conf
m.ball.minW = 8;  m.ball.maxAspect = 0.2;  m.ball.confSmall = 0.7;
m.robot.minH = 14;
m.ball.lqFac = {lq:.4g};  m.robot.lqFac = 1;   % extra std factor for LowQuality detections
m.ball.kB = {kb['ball']:.4g};  m.robot.kB = {kb['robot']:.4g};   % bearing std inflation
end
"""
open('../../eval/sensing/yoloErrorModel.m','w').write(out)
