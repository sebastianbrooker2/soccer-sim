function writeLatex(results, outDir, opts)
%WRITELATEX results_table.tex, fig_inregion_over_time.tex, fig_error_cdf.tex, main.tex
%   Figures read inregion_time.csv / err_cdf.csv (written by writeResults) with
%   \addplot table[col sep=comma]. opts.radius selects the within-radius column
%   (default 0.5). main.tex is a standalone example that \input's all three.
if nargin < 3, opts = struct(); end
radius = 0.5; if isfield(opts, 'radius'), radius = opts.radius; end
if ~exist(outDir, 'dir'), mkdir(outDir); end
S = results.summary;
if isempty(S) , S = aggregateMatches(results.perMatch); end
trk = unique(S.tracker, 'stable');
wm = ['within_' radiusTag(radius)];
% per class: in-95%-region, within radius, availability, false tracks, median area
mets = {'inRegion95',100,'%.1f'; wm,100,'%.1f'; 'availability',100,'%.1f'; 'falseTracks',1,'%.1f'; 'AREA',1,'%.1f'};
classes = {'ball','Ball'; 'opponent','Opponents'};
nM = size(mets,1);
f = fopen(fullfile(outDir, 'results_table.tex'), 'w');
fprintf(f, '%% generated by writeLatex.m\n\\begin{tabular}{l%s}\n\\toprule\n', repmat('c', 1, nM*size(classes,1)));
fprintf(f, ' & \\multicolumn{%d}{c}{Ball} & \\multicolumn{%d}{c}{Opponents} \\\\\n', nM, nM);
fprintf(f, '\\cmidrule(lr){2-%d}\\cmidrule(lr){%d-%d}\n', nM+1, nM+2, 2*nM+1);
hdr = sprintf('In 95\\%% region (\\%%) & Within %g\\,m (\\%%) & Avail.\\ (\\%%) & False tracks & Median area (m$^2$)', radius);
fprintf(f, 'Tracker & %s & %s \\\\\n\\midrule\n', hdr, hdr);
for a = 1:numel(trk)
    fprintf(f, '%s', texEsc(trk(a)));
    for c = 1:size(classes,1)
        for q = 1:nM
            mn = mets{q,1};
            if strcmp(mn, 'AREA')
                mn = 'region_area_recent_median';
                if ~any(S.metric == mn & S.class == classes{c,1}), mn = 'region_area_median'; end
            end
            m = S.tracker == trk(a) & S.class == classes{c,1} & S.metric == mn;
            if any(m) && ~isnan(S.mean(find(m,1)))
                fprintf(f, [' & $' mets{q,3} ' \\pm ' mets{q,3} '$'], mets{q,2}*S.mean(find(m,1)), mets{q,2}*S.std(find(m,1)));
            else
                fprintf(f, ' & --');
            end
        end
    end
    fprintf(f, ' \\\\\n');
end
fprintf(f, '\\bottomrule\n\\end{tabular}\n');
fclose(f);

names = {}; labels = {};
for a = 1:numel(trk)
    for cl = ["ball","opponent"]
        if any(S.tracker == trk(a) & S.class == cl)
            names{end+1} = colName(trk(a), cl); %#ok<AGROW>
            labels{end+1} = texEsc(sprintf('%s %s', trk(a), cl)); %#ok<AGROW>
        end
    end
end
writeFig(fullfile(outDir,'fig_inregion_over_time.tex'), 'inregion_time.csv', 't', names, labels, ...
    'Time (s)', 'In 95\% region', 'ymin=0,ymax=1');
writeFig(fullfile(outDir,'fig_error_cdf.tex'), 'err_cdf.csv', 'x', names, labels, ...
    'Error threshold (m)', 'Fraction of samples', 'ymin=0,ymax=1,xmin=0');

f = fopen(fullfile(outDir, 'main.tex'), 'w');
fprintf(f, ['\\documentclass{article}\n\\usepackage{booktabs}\n\\usepackage{graphicx}\n\\usepackage{pgfplots}\n' ...
    '\\usepackage{pgfplotstable}\n\\pgfplotsset{compat=1.16}\n\\begin{document}\n' ...
    '\\begin{table}[h]\\centering\\small\\resizebox{\\linewidth}{!}{\\input{results_table.tex}}\n\\caption{Tracking accuracy (mean $\\pm$ std over matches).}\n\\end{table}\n' ...
    '\\begin{figure}[h]\\centering\n\\input{fig_inregion_over_time.tex}\n\\end{figure}\n' ...
    '\\begin{figure}[h]\\centering\n\\input{fig_error_cdf.tex}\n\\end{figure}\n\\end{document}\n']);
fclose(f);
end

function writeFig(path, csv, xcol, names, labels, xl, yl, extra)
f = fopen(path, 'w');
fprintf(f, '%% generated by writeLatex.m; reads %s\n\\begin{tikzpicture}\n', csv);
fprintf(f, '\\begin{axis}[width=0.9\\linewidth,height=6cm,xlabel={%s},ylabel={%s},%s,legend pos=south east,grid=major,unbounded coords=discard]\n', xl, yl, extra);
for k = 1:numel(names)
    fprintf(f, '\\addplot table[col sep=comma,x=%s,y=%s]{%s};\n\\addlegendentry{%s}\n', xcol, names{k}, csv, labels{k});
end
fprintf(f, '\\end{axis}\n\\end{tikzpicture}\n');
fclose(f);
end

function s = texEsc(s)
s = char(s); s = strrep(s, '_', '\_'); s = strrep(s, '%', '\%');
end
